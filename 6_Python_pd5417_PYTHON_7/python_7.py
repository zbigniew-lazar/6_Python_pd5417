# Operacje arytmetyczne
eksony = 8
introny = 7

print("Dodawanie:", eksony + introny)
print("Odejmowanie:", eksony - introny)
print("Mnożenie:", eksony * introny)
print("Dzielenie:", eksony / introny)
print("Modulo:", eksony % introny)

# Operator przypisania
eksony += 2
print("Nowa liczba eksonów:", eksony)

# Operatory porównania
print("Czy eksony są równe intronom?", eksony == introny)
print("Czy eksony są większe od intronów?", eksony > introny)